const char* paramTooltip(const char* key)
{
  if (!key) return nullptr;
  const auto& t = tooltips();
  auto it = t.find(key);
  if (it != t.end()) return it->second;
  // Повторяющиеся группы используют общий текст: кабинет B — тексты A, полосы EQ — полосы 1, голоса — голоса 1
  std::string k(key);
  auto alias = [&](const char* prefix, const char* base) -> const char* {
    const size_t n = std::strlen(prefix);
    if (k.rfind(prefix, 0) != 0 || k.size() < n + 2) return nullptr;
    const size_t dot = k.find('.', n);
    if (dot == std::string::npos) return nullptr;
    auto f = t.find(std::string(base) + k.substr(dot));
    return f != t.end() ? f->second : nullptr;
  };
  if (k.rfind("cab.b.", 0) == 0)
  {
    it = t.find("cab.a." + k.substr(6));
    if (it != t.end()) return it->second;
  }
  if (const char* a = alias("eq.b", "eq.b1")) return a;
  if (const char* a = alias("harm.v", "harm.v1")) return a;
  // Переключатели модулей
  if (k.size() > 3 && k.compare(k.size() - 3, 3, ".on") == 0) return "Включить/выключить модуль. Переключение плавное, без щелчков.";
  return nullptr;
}

